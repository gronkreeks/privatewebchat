// Build tool: turns the UI files into ui.h, so the app is a single file with nothing beside it.
// Usage: embed <out.h> <dir> <file>...
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

static const char *type_of(const char *name) {
  const char *dot = strrchr(name, '.');
  if (!dot) return "application/octet-stream";
  if (!strcmp(dot, ".html")) return "text/html; charset=utf-8";
  if (!strcmp(dot, ".css")) return "text/css; charset=utf-8";
  if (!strcmp(dot, ".js")) return "text/javascript; charset=utf-8";
  if (!strcmp(dot, ".svg")) return "image/svg+xml";
  if (!strcmp(dot, ".png")) return "image/png";
  return "application/octet-stream";
}

int main(int argc, char **argv) {
  if (argc < 4) { fprintf(stderr, "usage: embed <out.h> <dir> <file>...\n"); return 1; }
  FILE *out = fopen(argv[1], "w");
  if (!out) { perror(argv[1]); return 1; }
  fprintf(out, "// Generated by embed.c from the ui/ folder. Don't edit.\n#include <stddef.h>\n"
               "struct ui_file { const char *path, *type; const unsigned char *data; size_t len; };\n");
  for (int i = 3; i < argc; i++) {
    char path[1024];
    snprintf(path, sizeof path, "%s/%s", argv[2], argv[i]);
    FILE *f = fopen(path, "rb");
    if (!f) { perror(path); return 1; }
    fprintf(out, "static const unsigned char ui_data_%d[] = {", i);
    int c;
    size_t n = 0;
    while ((c = fgetc(f)) != EOF) fprintf(out, "%s%d,", n++ % 24 ? "" : "\n", c);
    fprintf(out, "0};\n");
    fclose(f);
  }
  fprintf(out, "static const struct ui_file ui_files[] = {\n");
  for (int i = 3; i < argc; i++)
    fprintf(out, "  { \"%s\", \"%s\", ui_data_%d, sizeof ui_data_%d - 1 },\n", argv[i], type_of(argv[i]), i, i);
  fprintf(out, "};\nstatic const size_t ui_count = %d;\n", argc - 3);
  fclose(out);
  return 0;
}
